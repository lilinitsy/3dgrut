"""Generate the split-sum (A, B) table of the playground's own specular model for the cone path.

Run from the repo root: python scripts/cone/make_dfg_lut.py

The MC specular branch of sampled_microfacet_brdf is chosen with probability 0.5 and weighted by 2 (when
transmission is 0 the other half is diffuse), so its expectation is the single-branch expectation computed here:
w = G * (v.h) / max((n.h) * (n.v), 0.001) with Schlick-GGX Smith G, F = f0 + (1 - f0) * (1 - v.h)^5,
A = E[w * (1 - (1 - v.h)^5)], B = E[w * (1 - v.h)^5]. Stratified 256x256 samples over (rand.y, rand.x), no RNG.
"""

from pathlib import Path

import numpy as np

LUT_SIZE = 32
SAMPLES = 256
PBR_EPS = 1e-6  # materials.cuh PBR_EPS, only guards a zero denominator
OUT_PATH = Path(__file__).resolve().parents[2] / "threedgrut_playground/include/playground/kernels/cuda/dfgLut.cuh"


def _schlick_ggx(n_dot_v, roughness):
    alpha = 0.5 * roughness * roughness
    return n_dot_v / np.maximum(n_dot_v * (1.0 - alpha) + alpha, PBR_EPS)


def compute_cell(n_dot_v, roughness):
    """Returns (A, B) for one (nDotV, roughness) pair."""
    n_dot_v = max(n_dot_v, 1e-3)
    alpha = roughness * roughness
    u = (np.arange(SAMPLES, dtype=np.float64) + 0.5) / SAMPLES
    rand_y, rand_x = np.meshgrid(u, u, indexing="ij")  # rand_y: theta seed, rand_x: phi seed
    cos_t = np.sqrt((1.0 - rand_y) / (1.0 + (alpha * alpha - 1.0) * rand_y))
    theta = np.arccos(cos_t)
    phi = 2.0 * np.pi * rand_x
    h = np.stack([np.sin(theta) * np.cos(phi), np.sin(theta) * np.sin(phi), np.cos(theta)], axis=-1)
    v = np.array([np.sqrt(max(1.0 - n_dot_v * n_dot_v, 0.0)), 0.0, n_dot_v])
    v_dot_h_raw = h @ v
    light = 2.0 * v_dot_h_raw[..., None] * h - v  # reflect(-v, h)
    n_dot_h = np.clip(h[..., 2], 0.0, 1.0)
    n_dot_l = np.clip(light[..., 2], 0.0, 1.0)
    v_dot_h = np.clip(v_dot_h_raw, 0.0, 1.0)
    geometry = _schlick_ggx(n_dot_v, roughness) * _schlick_ggx(n_dot_l, roughness)
    weight = geometry * v_dot_h / np.maximum(n_dot_h * n_dot_v, 0.001)
    fresnel_pow = (1.0 - v_dot_h) ** 5
    return float(np.mean(weight * (1.0 - fresnel_pow))), float(np.mean(weight * fresnel_pow))


def compute_table():
    """Array [roughness j, nDotV i, 2]."""
    grid = np.arange(LUT_SIZE) / (LUT_SIZE - 1)
    table = np.zeros((LUT_SIZE, LUT_SIZE, 2), dtype=np.float32)
    for j, roughness in enumerate(grid):
        for i, n_dot_v in enumerate(grid):
            table[j, i] = compute_cell(float(n_dot_v), float(roughness))
    return table


def format_header(table):
    entries = [f"{{{a:.7e}f, {b:.7e}f}}" for a, b in table.reshape(-1, 2)]
    lines = ["  " + ", ".join(entries[k : k + 4]) for k in range(0, len(entries), 4)]
    body = ",\n".join(lines)
    return f"""// Generated by scripts/cone/make_dfg_lut.py (run: python scripts/cone/make_dfg_lut.py). Do not edit.
// Split-sum table of the playground specular model: expected specular weight = f0 * A + B.
// Row = roughness index j (roughness = j / 31), column = nDotV index i (nDotV = i / 31).

#ifndef PLAYGROUND_DFG_LUT_CUH
#define PLAYGROUND_DFG_LUT_CUH

static constexpr int DFG_LUT_SIZE = {LUT_SIZE};

static __device__ const float2 DFG_LUT[{LUT_SIZE} * {LUT_SIZE}] = {{
{body}
}};

static __device__ __inline__ float2 dfgLookup(const float nDotV, const float roughness)
{{
  const float x = fminf(fmaxf(nDotV, 0.0f), 1.0f) * (DFG_LUT_SIZE - 1);
  const float y = fminf(fmaxf(roughness, 0.0f), 1.0f) * (DFG_LUT_SIZE - 1);
  const int x0 = min(int(x), DFG_LUT_SIZE - 2);
  const int y0 = min(int(y), DFG_LUT_SIZE - 2);
  const float fx = x - x0;
  const float fy = y - y0;
  const float2 a = DFG_LUT[y0 * DFG_LUT_SIZE + x0];
  const float2 b = DFG_LUT[y0 * DFG_LUT_SIZE + x0 + 1];
  const float2 c = DFG_LUT[(y0 + 1) * DFG_LUT_SIZE + x0];
  const float2 d = DFG_LUT[(y0 + 1) * DFG_LUT_SIZE + x0 + 1];
  const float2 top = make_float2(a.x + (b.x - a.x) * fx, a.y + (b.y - a.y) * fx);
  const float2 bottom = make_float2(c.x + (d.x - c.x) * fx, c.y + (d.y - c.y) * fx);
  return make_float2(top.x + (bottom.x - top.x) * fy, top.y + (bottom.y - top.y) * fy);
}}

#endif
"""


if __name__ == "__main__":
    OUT_PATH.write_text(format_header(compute_table()), encoding="utf-8")
    print(f"wrote {OUT_PATH}")
